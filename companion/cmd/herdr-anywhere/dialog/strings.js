// The words for what `herdr-anywhere language` printed; anything else is English.
export function wordsFor(lang) {
  return STRINGS[String(lang ?? "").trim()] ?? STRINGS.en;
}

export function fill(text, vars) {
  return text.replace(/\{(\w+)\}/g, (all, name) => (vars && name in vars ? String(vars[name]) : all));
}
