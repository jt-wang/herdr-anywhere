for (const width of [375, 900, 1366]) test(`the chat toggle reflects the whole-tab canvas after splitting from chat at ${width}px`, async () => {
  const app = await open('./fixtures/fake.tsx', { width, height: 844, host: { params: { scene: 'single', argv: 'codex', status: 'working', chat: JSON.stringify({ chat: true, turns: [] }) } }, clock: {} })
  await app.clock.runFor(100)
  await app.press('id:space-sp1')
  await app.waitFor('id:show-chat')
  await app.press('id:show-chat')
  await app.waitFor('id:chat-view')
  await app.type('id:compose-input', 'Safe')
  app.onDialog((d) => d.buttons.includes('Split anyway') ? 'Split anyway' : null)
  await app.press('id:space-more')
  await app.press('id:menu-split-right')
  await app.waitFor('id:close-p-tb1')
  await app.clock.runFor(100)
  // The new shell is not a conversation; focusing its agent sibling must not open chat implicitly.
  expect(app.count('id:show-chat')).toBe(0)
  await app.press('id:pane-name-p-tb1')
  await app.clock.runFor(100)
  expect(app.count('id:terminal-t1')).toBe(1)
  expect(app.count('id:terminal-t2')).toBe(1)
  expect(app.count('id:chat-view')).toBe(0)
  expect(app.count('id:show-terminal')).toBe(0)
  expect(app.count('id:show-chat')).toBe(1)
  if (width === 1366) for (const folded of [900, 1366]) {
    await app.setViewport(folded, 844)
    await app.clock.runFor(100)
    expect(app.count('id:terminal-t2')).toBe(1)
    expect(app.count('id:chat-view')).toBe(0)
    expect(app.count('id:show-chat')).toBe(1)
  }
  // One tap changes the presentation, not the split or its unsent draft.
  await app.press('id:show-chat')
  await app.waitFor('id:chat-view')
  expect(app.count('id:close-p-tb1')).toBe(0)
  expect(app.value('id:compose-input')).toBe('Safe')
  await app.press('id:show-terminal')
  // Only 1366px leaves a genuinely wide detail column after the sidebar.
  if (width !== 1366) {
    await app.press('id:space-more')
    await app.press('id:menu-show-all')
  }
  await app.waitFor('id:close-p-tb1')
  await app.waitFor('id:terminal-t2')
})

