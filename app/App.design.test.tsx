test('a visible chat approval owns its attention accent; the sidebar regains it when the card is covered or closed', async () => {
  const app = await open('./fixtures/fake.tsx', { width: 900, colorScheme: 'dark', host: { params: { scene: 'busy', chat: JSON.stringify({ chat: true, turns: [{ id: 'u1', from: 'you', said: 'Review the sample login change.', end: 'open', reply: '', steps: [] }] }) } }, clock: {} })
  await app.clock.runFor(100)
  await app.waitFor('id:needs-t1')
  const attention = () => app.spanStyle('id:needs-t1 >> text:!').color
  const warm = attention()
  const quiet = app.spanStyle('id:status-line >> text:This computer').color
  // The headless engine uses its neutral default palette; compare semantic roles, not packaged theme hexes.
  expect(warm === quiet).toBe(false)
  await app.press('id:space-sp1')
  await app.waitFor('id:show-chat')
  await app.press('id:show-chat')
  await app.waitFor('id:ask-card')
  expect(attention()).toBe(quiet)
  await app.press('id:space-more')
  await app.waitFor('id:menu')
  expect(attention()).toBe(warm)
  await app.press('id:menu-cancel')
  await app.clock.runFor(400)
  expect(attention()).toBe(quiet)
  await app.press('id:settings')
  await app.waitFor('id:forget')
  expect(attention()).toBe(warm)
  await app.press('id:back')
  await app.waitFor('id:ask-card')
  expect(attention()).toBe(quiet)
  await app.press('id:show-terminal')
  await app.waitUntil(() => app.count('id:ask-card') === 0)
  expect(attention()).toBe(warm)
})

test('reading earlier turns restores sidebar attention until the approval heading is visible again', async () => {
  const turns = Array.from({ length: 18 }, (_, i) => ({ id: `u${i}`, from: 'you', said: `Sample question ${i}`, end: i === 17 ? 'open' : 'done', reply: 'Sample reply. '.repeat(12), steps: [] }))
  const app = await open('./fixtures/fake.tsx', { width: 900, height: 844, colorScheme: 'dark', host: { params: { scene: 'busy', chat: JSON.stringify({ chat: true, turns }) } }, clock: {} })
  await app.clock.runFor(100)
  await app.waitFor('id:needs-t1')
  const attention = () => app.spanStyle('id:needs-t1 >> text:!').color
  const warm = attention()
  const quiet = app.spanStyle('id:status-line >> text:This computer').color
  expect(warm === quiet).toBe(false)
  await app.press('id:space-sp1')
  await app.clock.runFor(100)
  await app.press('id:show-chat')
  await app.waitFor('id:ask-card')
  await app.clock.runFor(200)
  expect(attention()).toBe(quiet)
  await app.scroll('id:chat-scroll', -100000)
  await app.clock.runFor(100)
  expect(attention()).toBe(warm)
  await app.scroll('id:chat-scroll', 100000)
  await app.clock.runFor(100)
  expect(attention()).toBe(quiet)
})
