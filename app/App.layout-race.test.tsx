import { expect, open, test } from 'nsh/test'

test('Root keeps the new terminal after a competing layout write and sends input to it', async () => {
  const app = await open('./fixtures/fake.tsx', { host: { params: { scene: 'layout-race' } } })
  await app.waitFor('id:space-splayout')
  await app.press('id:space-splayout')
  await app.press('id:layout-arm')
  await app.press('id:switcher')
  await app.press('id:switch-new-shell')
  await app.waitFor('id:layout-blocked')
  await app.press('id:layout-snapshot')
  const shown = JSON.parse(app.storage()['layout-evidence'])
  expect(shown.stage).toBe('visible')
  expect(shown.focused).toBe(shown.originalPane)
  expect(app.count(`id:terminal-${shown.terminal}`)).toBe(1)
  // Android screenshot/dump work can outlast an RPC timeout while Release is waiting for a tap.
  await app.wait(22000)
  await app.press('id:layout-release')
  await app.waitFor('id:layout-released')
  const after = JSON.parse(app.storage()['layout-evidence'])
  expect(after.conflicts).toBe(1)
  expect(after.rename).toBe('grove')
  expect(after.pane).toBe(shown.originalPane)
  expect(after.focused).toBe(shown.originalPane)
  expect(after.documentPanes).toEqual([shown.originalPane])
  expect(after.runs).toBe(1)
  expect(app.count(`id:terminal-${shown.terminal}`)).toBe(1)
  await app.type('id:compose-input', 'layout input ok')
  await app.press('id:compose-send')
  await app.waitUntil(() => app.storage()['fake-sent'] === JSON.stringify([[shown.terminal, 'layout input ok', true]]))
  await app.press('id:layout-snapshot')
  const input = JSON.parse(app.storage()['layout-evidence'])
  expect(input.input).toEqual([shown.terminal, 'layout input ok'])
  expect(input.screen).toBe('layout input ok')
})
